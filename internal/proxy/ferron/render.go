// Render translates the engine-agnostic desired-state IR into Ferron 3
// configuration files keyed relative to /etc/ferron/nd ("ferron.conf" and
// deterministic "sites/*.conf" files).
func (d *Driver) Render(st *proxy.State) (proxy.Files, error) {
	if st == nil {
		return nil, fmt.Errorf("ferron: state is nil")
	}

	files := make(proxy.Files)
	mainConf, err := d.renderMainConfig(st)
	if err != nil {
		return nil, err
	}
	files["ferron.conf"] = mainConf

	idx := 0
	// strict_hosts rejects the whole configuration when one host label appears in two blocks
	// (e.g. the same domain added twice to a site), so the first site to claim a host keeps it.
	claimed := map[string]bool{}
	if st.Panel != nil {
		panelCopy := *st.Panel
		if strings.TrimSpace(panelCopy.ID) == "" {
			panelCopy.ID = "panel"
		}
		panelCopy.Hosts = claimHosts(panelCopy.Hosts, claimed)
		filename, content, err := d.renderSiteFile(idx, panelCopy, st.ACMEEmail)
		if err != nil {
			return nil, fmt.Errorf("ferron: render panel site: %w", err)
		}
		files[filename] = content
		idx++
	}

	sites := sortedSitesCopy(st.Sites)
	for _, s := range sites {
		if s.PHP != nil && s.PHP.Suspended {
			continue
		}
		s.Hosts = claimHosts(s.Hosts, claimed)
		if len(s.Hosts) == 0 {
			continue
		}
		filename, content, err := d.renderSiteFile(idx, s, st.ACMEEmail)
		if err != nil {
			return nil, fmt.Errorf("ferron: render site %q: %w", s.ID, err)
		}
		if existing, dup := files[filename]; dup && existing != "" {
			filename = fmt.Sprintf("sites/%03d-%s.conf", idx, siteSlug(s.ID, idx))
		}
		files[filename] = content
		idx++
	}

	if gwContent, ok, err := d.renderGatewaysFile(st.Gateways); err != nil {
		return nil, fmt.Errorf("ferron: render gateways: %w", err)
	} else if ok {
		files["sites/999-gateways.conf"] = gwContent
	}

	return files, nil
}

func (d *Driver) renderMainConfig(st *proxy.State) (string, error) {
	var b strings.Builder
	b.WriteString("# Generated by NextDeploy Ferron driver (experimental). Do not edit by hand.\n\n")
	b.WriteString("{\n")
	b.WriteString("    strict_hosts\n")
	b.WriteString("    admin {\n")
	fmt.Fprintf(&b, "        listen %s\n", quoteString(d.effectiveAdminSocketAddr()))
	fmt.Fprintf(&b, "        auth_token %s\n", quoteString("{{env."+d.adminTokenEnv+"}}"))
	b.WriteString("    }\n")

	b.WriteString("    http {\n")
	b.WriteString("        protocols h1 h2\n")
	b.WriteString("        timeout \"3660s\"\n")
	if maxHdrBytes := parseHeaderSizeBytes(st.Global.MaxHeaderSize); maxHdrBytes > 0 {
		fmt.Fprintf(&b, "        h2_max_header_list_size %d\n", maxHdrBytes)
	}
	b.WriteString("    }\n")

	if trusted := collectTrustedCIDRs(st.Global); len(trusted) > 0 {
		b.WriteString("    client_ip_from_header x-forwarded-for {\n")
		for _, cidr := range trusted {
			fmt.Fprintf(&b, "        trusted_proxy %s\n", quoteString(cidr))
		}
		b.WriteString("    }\n")
	}
	b.WriteString("}\n\n")

	writeSharedMatchers(&b)
	b.WriteString("include \"sites/*.conf\"\n")
	return b.String(), nil
}

func (d *Driver) renderSiteFile(idx int, s proxy.Site, acmeEmail string) (string, string, error) {
	filename := siteFilename(s.ID, idx)
	if s.ID == "panel" {
		filename = "sites/000-panel.conf"
	}
	slug := siteSlug(s.ID, idx)
	var b strings.Builder

	var err error
	switch s.Kind {
	case proxy.SiteKindPHP, proxy.SiteKindStatic:
		err = d.renderPHPSite(&b, slug, s, acmeEmail)
	case proxy.SiteKindRedirect:
		err = d.renderRedirectSite(&b, slug, s, acmeEmail)
	case proxy.SiteKindAppProxy, proxy.SiteKindExternalProxy, "":
		err = d.renderAppProxySite(&b, slug, s, acmeEmail)
	default:
		err = fmt.Errorf("unsupported site kind %q", s.Kind)
	}
	if err != nil {
		return "", "", err
	}
	b.WriteString(httpsRedirectBlock(s))
	return filename, b.String(), nil
}

func (d *Driver) effectiveAdminSocketAddr() string {
	addr := parseAdminListenAddr(d.adminURL)
	host, port, err := net.SplitHostPort(addr)
	if err != nil || net.ParseIP(host) == nil {
		if p := parsePositiveIntPort(port); p > 0 {
			return fmt.Sprintf("127.0.0.1:%d", p)
		}
		return "127.0.0.1:8081"
	}
	return addr
}

func writeSharedMatchers(b *strings.Builder) {
	b.WriteString("match ND_PHP_PATHINFO {\n")
	b.WriteString("    request.uri.path ~ r\"\\.php/\"\n")
	b.WriteString("}\n\n")

	b.WriteString("match ND_HIDDEN_FILES {\n")
	b.WriteString("    request.uri.path !~ r\"^/\\.well-known(?:/|$)\"\n")
	b.WriteString("    request.uri.path ~ r\"(?i)(?:^|/)\\.[^/]+|\\.(?:bak|conf|config|dist|env|git|htaccess|htpasswd|ini|log|orig|pem|key|sh|sql|swp|yml|yaml)$|(?:^|/)(?:composer\\.(?:json|lock)|package(?:-lock)?\\.json|wp-config\\.php|readme\\.(?:html|md)|license\\.txt)$\"\n")
	b.WriteString("}\n\n")

	b.WriteString("match ND_MEDIA_EXT {\n")
	b.WriteString("    request.uri.path ~ r\"(?i)\\.(?:avif|webp|jpe?g|png|gif|svg|ico|woff2?|ttf|eot|mp4|webm|ogg|mp3)$\"\n")
	b.WriteString("}\n\n")

	b.WriteString("match ND_CODE_EXT {\n")
	b.WriteString("    request.uri.path ~ r\"(?i)\\.(?:css|js|mjs|map|json|xml|txt)$\"\n")
	b.WriteString("}\n\n")

	b.WriteString("match ND_XMLRPC {\n")
	b.WriteString("    request.uri.path == \"/xmlrpc.php\"\n")
	b.WriteString("}\n\n")

	b.WriteString("match ND_UPLOAD_PHP {\n")
	b.WriteString("    request.uri.path ~ r\"(?i)(?:/wp-content/uploads/|/uploads/).*\\.php(?:/|$)\"\n")
	b.WriteString("}\n\n")

	b.WriteString("match ND_SCANNER_UA {\n")
	b.WriteString("    request.header.user_agent ~ r\"(?i)(?:sqlmap|nikto|nessus|acunetix|masscan|nmap|wpscan|dirbuster|gobuster|nuclei|zgrab|httpx)\"\n")
	b.WriteString("}\n\n")
}

func collectTrustedCIDRs(g proxy.GlobalOptions) []string {
	var raw []string
	if strings.EqualFold(strings.TrimSpace(g.RealIP), "cloudflare") || g.DirectCloudflare {
		raw = append(raw, proxy.CloudflareRanges...)
	}
	raw = append(raw, g.TrustedProxies...)
	raw = append(raw, g.ShieldProxies...)
	if len(raw) == 0 {
		return nil
	}
	norm, err := proxy.NormalizeIPList(raw)
	if err == nil && len(norm) > 0 {
		sort.Strings(norm)
		return norm
	}
	seen := make(map[string]bool, len(raw))
	var out []string
	for _, item := range raw {
		s := strings.TrimSpace(item)
		if s == "" || seen[s] {
			continue
		}
		seen[s] = true
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

func sortedSitesCopy(in []proxy.Site) []proxy.Site {
	if len(in) == 0 {
		return nil
	}
	out := make([]proxy.Site, len(in))
	copy(out, in)
	sort.Slice(out, func(i, j int) bool {
		if out[i].ID != out[j].ID {
			return out[i].ID < out[j].ID
		}
		return strings.Join(out[i].Hosts, ",") < strings.Join(out[j].Hosts, ",")
	})
	return out
}

func parseHeaderSizeBytes(raw string) int64 {
	s := strings.ToLower(strings.TrimSpace(raw))
	if s == "" {
		return 0
	}
	mult := int64(1)
	switch {
	case strings.HasSuffix(s, "kib") || strings.HasSuffix(s, "kb"):
		mult = 1024
		s = strings.TrimSuffix(strings.TrimSuffix(s, "kib"), "kb")
	case strings.HasSuffix(s, "mib") || strings.HasSuffix(s, "mb"):
		mult = 1024 * 1024
		s = strings.TrimSuffix(strings.TrimSuffix(s, "mib"), "mb")
	case strings.HasSuffix(s, "k"):
		mult = 1024
		s = strings.TrimSuffix(s, "k")
	case strings.HasSuffix(s, "m"):
		mult = 1024 * 1024
		s = strings.TrimSuffix(s, "m")
	case strings.HasSuffix(s, "b"):
		s = strings.TrimSuffix(s, "b")
	}
	n, err := strconv.ParseInt(strings.TrimSpace(s), 10, 64)
	if err != nil || n <= 0 {
		return 0
	}
	return n * mult
}

// claimHosts returns the hosts not yet claimed by an earlier site and marks them claimed.
func claimHosts(hosts []string, claimed map[string]bool) []string {
	out := make([]string, 0, len(hosts))
	for _, raw := range hosts {
		key := strings.ToLower(strings.TrimSpace(proxy.CleanQuotedValue(raw)))
		key = strings.TrimPrefix(key, "http ")
		if key == "" || claimed[key] {
			continue
		}
		claimed[key] = true
		out = append(out, raw)
	}
	return out
}
